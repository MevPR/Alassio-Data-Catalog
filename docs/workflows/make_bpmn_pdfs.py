"""Builds the BPMN files and BPMN PDFs served under /docs (v1.79):
    python3 docs/workflows/make_bpmn_pdfs.py <public/docs> <version>
  · Alassio_Data_Product_Design.bpmn + Alassio_Data_Product_Design_BPMN.pdf — generated by make_design_bpmn.py
  · Alassio_Other_Workflows_BPMN.pdf — the access request and steward task, rendered from their .bpmn files
    (Alassio_Access_Request.bpmn, Alassio_Steward_Description_Request.bpmn are the source of truth)
Needs reportlab + svglib (pip install reportlab svglib). Regenerate only when asked (not part of the release routine)."""
import os
import shutil
import subprocess
import sys
import tempfile

from reportlab.graphics import renderPDF
from reportlab.lib import colors
from reportlab.lib.pagesizes import A3, A4, landscape
from reportlab.lib.units import mm
from reportlab.pdfgen import canvas
from svglib.svglib import svg2rlg

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from bpmn_render import render  # noqa: E402
from bpmnlib import BRAND  # noqa: E402

OUT = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "..", "..", "public", "docs")
VERSION = sys.argv[2] if len(sys.argv) > 2 else "current"
FOOT = f"COMPANY Group · Alassio Data Catalog v{VERSION} · BPMN 2.0 — the .bpmn files open in Camunda Modeler, bpmn.io or Signavio"


def page(c, svg, size):
    w, h = size
    c.setPageSize(size)
    c.setFillColor(colors.HexColor(BRAND)); c.rect(0, h - 5 * mm, w, 5 * mm, stroke=0, fill=1)
    d = svg2rlg(svg)
    avail_w, avail_h = w - 20 * mm, h - 24 * mm
    k = min(avail_w / d.width, avail_h / d.height)
    d.width, d.height = d.width * k, d.height * k
    d.scale(k, k)
    renderPDF.draw(d, c, (w - d.width) / 2, 12 * mm + (avail_h - d.height) / 2)
    c.setFillColor(colors.HexColor("#6B6F73")); c.setFont("Helvetica", 7.5)
    c.drawString(10 * mm, 6 * mm, FOOT)
    c.drawRightString(w - 10 * mm, 6 * mm, f"Page {c.getPageNumber()}")
    c.showPage()


tmp = tempfile.mkdtemp()
subprocess.run([sys.executable, os.path.join(HERE, "make_design_bpmn.py"), tmp, VERSION], check=True)
shutil.copy(os.path.join(tmp, "Alassio_Data_Product_Design.bpmn"), os.path.join(OUT, "Alassio_Data_Product_Design.bpmn"))
c = canvas.Canvas(os.path.join(OUT, "Alassio_Data_Product_Design_BPMN.pdf"))
c.setTitle(f"Alassio Data Catalog — Data product design (BPMN, v{VERSION})")
page(c, os.path.join(tmp, "bpmn_design.svg"), landscape(A3))
c.save()

c = canvas.Canvas(os.path.join(OUT, "Alassio_Other_Workflows_BPMN.pdf"))
c.setTitle(f"Alassio Data Catalog — access request and steward task (BPMN, v{VERSION})")
for name, title in (("Alassio_Access_Request", "Access request — BPMN view"), ("Alassio_Steward_Description_Request", "Steward task: describe attributes — BPMN view")):
    svg = os.path.join(tmp, f"{name}.svg")
    render(os.path.join(OUT, f"{name}.bpmn"), svg, f"{title} (Alassio Data Catalog v{VERSION})")
    page(c, svg, landscape(A4))
c.save()
shutil.rmtree(tmp)
print("bpmn pdfs ok")
